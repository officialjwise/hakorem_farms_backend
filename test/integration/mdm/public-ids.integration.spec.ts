import { randomUUID } from 'node:crypto';
import { ManualClock } from '@hakorem/kernel';
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { PublicIds } from '../../../src/modules/mdm/application/public-ids';
import { consoleGet, consolePatch, consolePost, createBranch, createUser, enrolAndLogin, relaxRateLimits, testStartTime, type TestSession } from '../../support/iam';
import { startTestApp, type TestApp } from '../../support/test-app';
import { createTestDatabase, type TestDatabase } from '../../support/test-database';

/**
 * Customers and suppliers carry an unguessable public ID in place of their sequential numbers (B09q, owner
 * 2026-11-17, ADR-0073): generated by the server from a secure source, tried again on a collision, shown in every
 * answer, found by search however it is typed, and never taken as input. The sequential numbers stay in their columns.
 */
const CUSTOMER_ID = /^cus_[0-9A-HJKMNP-TV-Z]{16}$/;
const SUPPLIER_ID = /^sup_[0-9A-HJKMNP-TV-Z]{16}$/;
let database: TestDatabase;
let api: TestApp;
let manager: TestSession;
let phone = 0;

const post = (path: string, body: object) => consolePost(api.server, manager, `/v1${path}`, randomUUID()).send(body);
const get = (path: string) => consoleGet(api.server, manager, `/v1${path}`);
const nextPhone = () => `0244${String(600_000 + (phone += 1)).padStart(6, '0')}`;
const customer = (name: string) => post('/customers', { kind: 'INDIVIDUAL', name, phone: nextPhone() });
const supplier = (name: string) => post('/suppliers', { name, phone: nextPhone() });
const count = async (table: string) => Number((await database.pool('admin').query<{ n: string }>(`SELECT count(*) AS n FROM ${table}`)).rows[0]!.n);
/** "cus_8F3K2M9Q7X4T1V6B" as a person might type it: lower case, spaced in fours, 0 as O and 1 as I. */
const typedLoosely = (publicId: string) => `${publicId.slice(0, 4)}${publicId.slice(4).toLowerCase().replace(/(.{4})/g, '$1 ').trim().replaceAll('0', 'o').replaceAll('1', 'i')}`;

beforeAll(async () => {
  database = await createTestDatabase();
  const clock = new ManualClock(testStartTime());
  await relaxRateLimits(database);
  api = await startTestApp(database, { clock });
  const dodowa = await createBranch(database);
  manager = await enrolAndLogin(api.server, await createUser(database, { name: 'Kwabena Owusu', grants: [{ role: 'MANAGER', branchId: dodowa.branchId }] }), () => clock.now());
});

afterEach(() => {
  vi.restoreAllMocks();
});

afterAll(async () => {
  await api.close();
  await database.drop();
});

describe('a public ID in place of the sequential number', () => {
  it('answers a new customer and a new supplier with a public ID of their kind and no sequential number, which stays internal', async () => {
    const ama = await customer('Ama Serwaa');
    expect(ama.status, JSON.stringify(ama.body)).toBe(201);
    expect(ama.body.publicId).toMatch(CUSTOMER_ID);
    expect(ama.body).not.toHaveProperty('customerNo');
    const awutu = await supplier('Awutu Poultry Farm');
    expect(awutu.status, JSON.stringify(awutu.body)).toBe(201);
    expect(awutu.body.publicId).toMatch(SUPPLIER_ID);
    expect(awutu.body).not.toHaveProperty('supplierNo');
    const stored = await database.pool('admin').query<{ public_id: string; customer_no: string }>('SELECT public_id, customer_no FROM mdm.customer WHERE id = $1', [ama.body.id]);
    expect(stored.rows[0]).toEqual({ public_id: ama.body.publicId, customer_no: expect.stringMatching(/^C-\d{5}$/) });
    expect((await get(`/customers/${ama.body.id}`)).body.publicId).toBe(ama.body.publicId);
    expect((await get(`/suppliers/${awutu.body.id}`)).body.publicId).toBe(awutu.body.publicId);
  });

  it('gives every customer a different public ID', async () => {
    const created = await Promise.all(Array.from({ length: 6 }, (_, i) => customer(`Kofi Mensah ${i + 1}`)));
    expect(created.map((r) => r.status)).toEqual(Array(6).fill(201));
    expect(new Set(created.map((r) => r.body.publicId)).size).toBe(6);
  });

  it('finds a customer and a supplier by public ID however it is typed, and nothing by a sequential number', async () => {
    const abena = await customer('Abena Ofori');
    const tema = await supplier('Tema Cattle Traders');
    for (const q of [abena.body.publicId as string, typedLoosely(abena.body.publicId as string)]) {
      const found = await get(`/customers?q=${encodeURIComponent(q)}`);
      expect(found.status).toBe(200);
      expect(found.body.data.map((c: { id: string }) => c.id), q).toEqual([abena.body.id]);
    }
    const bySupplierId = await get(`/suppliers?q=${encodeURIComponent(typedLoosely(tema.body.publicId as string))}`);
    expect(bySupplierId.body.data.map((s: { id: string }) => s.id)).toEqual([tema.body.id]);
    const number = (await database.pool('admin').query<{ n: string }>('SELECT customer_no AS n FROM mdm.customer WHERE id = $1', [abena.body.id])).rows[0]!.n;
    expect((await get(`/customers?q=${number}`)).body.data).toEqual([]);
    // A supplier's ID does not find a customer, nor a customer's a supplier.
    expect((await get(`/customers?q=${encodeURIComponent(tema.body.publicId as string)}`)).body.data).toEqual([]);
    expect((await get(`/suppliers?q=${encodeURIComponent(abena.body.publicId as string)}`)).body.data).toEqual([]);
  });

  it('takes no public ID as input: a create or an update that sends one is 400 and changes nothing', async () => {
    const before = await count('mdm.customer');
    const refused = await post('/customers', { kind: 'INDIVIDUAL', name: 'Yaw Asante', publicId: 'cus_8F3K2M9Q7X4T1V6B' });
    expect(refused.status).toBe(400);
    expect(refused.body.error.details).toEqual(expect.arrayContaining([expect.objectContaining({ field: '/publicId', code: 'UNKNOWN_FIELD' })]));
    expect(await count('mdm.customer')).toBe(before);
    const yaw = await customer('Yaw Asante');
    const patched = await consolePatch(api.server, manager, `/v1/customers/${yaw.body.id}`).send({ version: yaw.body.version, publicId: 'cus_8F3K2M9Q7X4T1V6B' });
    expect(patched.status).toBe(400);
    expect((await get(`/customers/${yaw.body.id}`)).body).toMatchObject({ publicId: yaw.body.publicId, version: yaw.body.version });
  });
});

describe('a collision with another public ID is tried again (ADR-0073)', () => {
  it('creates the customer with a fresh public ID when the first drawn is one another customer holds', async () => {
    const taken = (await customer('Efua Darko')).body.publicId as string;
    const ids = api.app.get(PublicIds);
    const real = ids.next.bind(ids);
    const next = vi.spyOn(ids, 'next').mockImplementationOnce(() => taken).mockImplementation(real);
    const created = await customer('Efua Darko-Addo');
    expect(created.status, JSON.stringify(created.body)).toBe(201);
    expect(created.body.publicId).toMatch(CUSTOMER_ID);
    expect(created.body.publicId).not.toBe(taken);
    expect(next).toHaveBeenCalledTimes(2);
  });

  it('creates the supplier with a fresh public ID when the first two drawn are taken', async () => {
    const taken = (await supplier('Ho Produce Growers')).body.publicId as string;
    const ids = api.app.get(PublicIds);
    const real = ids.next.bind(ids);
    vi.spyOn(ids, 'next').mockImplementationOnce(() => taken).mockImplementationOnce(() => taken).mockImplementation(real);
    const created = await supplier('Ho Produce Growers 2');
    expect(created.status, JSON.stringify(created.body)).toBe(201);
    expect(created.body.publicId).not.toBe(taken);
  });

  it('gives up after five collisions with a 500, and writes nothing', async () => {
    const taken = (await customer('Kojo Appiah')).body.publicId as string;
    vi.spyOn(api.app.get(PublicIds), 'next').mockImplementation(() => taken);
    const before = await count('mdm.customer');
    const refused = await customer('Kojo Appiah Jr');
    expect(refused.status).toBe(500);
    expect(refused.body.error.code).toBe('INTERNAL');
    expect(await count('mdm.customer')).toBe(before);
  });
});
